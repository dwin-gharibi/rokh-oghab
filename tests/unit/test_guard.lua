local h = require("harness")
local guard = require("ro.guard")
local target = require("ro.target")

local function must_block(g, host, why)
    local info, err = target.classify_host(host)
    h.assert_true(info, "classify " .. host .. ": " .. tostring(err))
    local ok, reason = g:check(info)
    h.assert_false(ok, (why or host) .. " must be blocked")
    h.assert_true(reason, "block reason must be reported for " .. host)
end

local function must_allow(g, host)
    local info, err = target.classify_host(host)
    h.assert_true(info, "classify " .. host .. ": " .. tostring(err))
    local ok, reason = g:check(info)
    h.assert_true(ok, host .. " must be allowed, blocked by " .. tostring(reason))
end

h.describe("guard default deny of internal address space", function()
    local g = assert(guard.new())

    h.it("blocks loopback", function()
        must_block(g, "127.0.0.1")
        must_block(g, "127.255.255.254")
        must_block(g, "[::1]")
    end)

    h.it("blocks link-local and cloud metadata endpoints", function()
        must_block(g, "169.254.169.254", "AWS/GCP/Azure IMDS")
        must_block(g, "169.254.170.2", "ECS task metadata")
        must_block(g, "169.254.169.123", "AWS time sync")
        must_block(g, "100.100.100.200", "Alibaba metadata")
        must_block(g, "192.0.0.192", "Oracle metadata")
        must_block(g, "[fd00:ec2::254]", "EC2 IPv6 IMDS")
    end)

    h.it("blocks RFC1918 and CGNAT space", function()
        must_block(g, "10.0.0.1")
        must_block(g, "10.255.255.255")
        must_block(g, "172.16.0.1")
        must_block(g, "172.31.255.255")
        must_block(g, "192.168.1.1")
        must_block(g, "100.64.0.1")
    end)

    h.it("blocks unspecified, broadcast, multicast and reserved space", function()
        must_block(g, "0.0.0.0")
        must_block(g, "0.1.2.3")
        must_block(g, "255.255.255.255")
        must_block(g, "224.0.0.1")
        must_block(g, "239.255.255.255")
        must_block(g, "240.0.0.1")
        must_block(g, "198.18.0.1")
    end)

    h.it("blocks internal ipv6 ranges", function()
        must_block(g, "[fc00::1]")
        must_block(g, "[fd12:3456::1]")
        must_block(g, "[fe80::1]")
        must_block(g, "[ff02::1]")
        must_block(g, "[::]")
        must_block(g, "[2001:db8::1]")
    end)

    h.it("blocks ipv6 tunnel encodings of internal ipv4", function()
        must_block(g, "[::ffff:127.0.0.1]", "v4-mapped loopback")
        must_block(g, "[::ffff:169.254.169.254]", "v4-mapped IMDS")
        must_block(g, "[::127.0.0.1]", "v4-compatible loopback")
        must_block(g, "[2002:7f00:0001::]", "6to4 loopback")
        must_block(g, "[2002:a9fe:a9fe::]", "6to4 IMDS")
        must_block(g, "[64:ff9b::169.254.169.254]", "NAT64 IMDS")
        must_block(g, "[fe80::5efe:169.254.169.254]", "ISATAP IMDS")
    end)

    h.it("blocks obfuscated literal encodings", function()
        must_block(g, "2130706433", "decimal loopback")
        must_block(g, "0x7f000001", "hex loopback")
        must_block(g, "017700000001", "octal loopback")
        must_block(g, "127.1", "short-form loopback")
        must_block(g, "0xa9fea9fe", "hex IMDS")
        must_block(g, "2852039166", "decimal IMDS")
        must_block(g, "169.254.43518", "short-form IMDS")
    end)

    h.it("allows genuinely public addresses", function()
        must_allow(g, "1.1.1.1")
        must_allow(g, "8.8.8.8")
        must_allow(g, "93.184.216.34")
        must_allow(g, "151.101.0.223")
        must_allow(g, "[2606:4700:4700::1111]")
        must_allow(g, "[2a00:1450:4001:80f::200e]")
    end)
end)

h.describe("guard obfuscation policy", function()
    h.it("rejects every obfuscated literal even when public", function()
        local g = assert(guard.new())
        must_block(g, "16909060", "decimal form of 1.2.3.4")
        must_block(g, "0x08080808", "hex form of 8.8.8.8")
    end)

    h.it("can be relaxed to canonicalise instead of reject", function()
        local g = assert(guard.new({ block_obfuscated = false }))
        must_allow(g, "16909060")
        must_block(g, "2130706433", "still resolves to loopback")
    end)
end)

h.describe("guard embedded ipv4 unwrapping without default prefixes", function()
    local g = assert(guard.new({
        include_defaults = false,
        blocked = { "127.0.0.0/8", "169.254.0.0/16" },
    }))

    h.it("still blocks tunnelled internal ipv4", function()
        must_block(g, "[2002:7f00:0001::]", "6to4 loopback")
        must_block(g, "[64:ff9b::169.254.169.254]", "NAT64 IMDS")
        must_block(g, "[::ffff:127.0.0.1]", "v4-mapped loopback")
        must_block(g, "[fe80::5efe:127.0.0.1]", "ISATAP loopback")
        must_block(g, "[::ffff:0:127.0.0.1]", "v4-translated loopback")
    end)

    h.it("permits unrelated ipv6", function()
        must_allow(g, "[2606:4700:4700::1111]")
    end)
end)

h.describe("guard operator overrides", function()
    h.it("honours explicit allow exceptions", function()
        local g = assert(guard.new({
            allow_exceptions = { "10.10.0.0/16" },
        }))
        must_allow(g, "10.10.1.1")
        must_block(g, "10.11.1.1", "outside the exception")
    end)

    h.it("accepts additional operator block ranges", function()
        local g = assert(guard.new({
            blocked = { "203.0.200.0/24", "8.8.8.8/32" },
        }))
        must_block(g, "203.0.200.5")
        must_block(g, "8.8.8.8")
        must_allow(g, "8.8.4.4")
    end)

    h.it("can disable ipv6 entirely", function()
        local g = assert(guard.new({ allow_ipv6 = false }))
        must_block(g, "[2606:4700:4700::1111]", "ipv6 disabled")
        must_allow(g, "1.1.1.1")
    end)

    h.it("rejects invalid configuration", function()
        local g, err = guard.new({ blocked = { "not-a-cidr" } })
        h.assert_nil(g)
        h.assert_match(err, "invalid cidr")
    end)
end)
