local h = require("harness")
local metrics = require("ro.metrics")

h.describe("metrics registry", function()
    h.it("initialises against a shared dictionary", function()
        h.assert_true(metrics.init("ro_metrics", { max_series = 100 }))
        metrics.reset()
        metrics.define("test_counter", "counter", "A counter for tests.")
        metrics.define("test_gauge", "gauge", "A gauge for tests.")
        metrics.define("test_hist", "histogram", "A histogram for tests.",
            { 0.1, 1, 10 })
    end)

    h.it("reports an error for a missing dictionary", function()
        local ok, err = metrics.init("does_not_exist")
        h.assert_nil(ok)
        h.assert_match(err, "shared dict")
        metrics.init("ro_metrics", { max_series = 100 })
    end)
end)

h.describe("metrics counters", function()
    h.it("increments and accumulates", function()
        metrics.reset()
        metrics.inc("test_counter", { action = "allow" })
        metrics.inc("test_counter", { action = "allow" })
        metrics.inc("test_counter", { action = "deny" }, 5)
        h.assert_eq(metrics.get("test_counter", { action = "allow" }), 2)
        h.assert_eq(metrics.get("test_counter", { action = "deny" }), 5)
    end)

    h.it("ignores non-positive increments", function()
        metrics.reset()
        metrics.inc("test_counter", nil, 0)
        metrics.inc("test_counter", nil, -3)
        h.assert_nil(metrics.get("test_counter", nil))
    end)

    h.it("keeps label sets distinct and order independent", function()
        metrics.reset()
        metrics.inc("test_counter", { a = "1", b = "2" })
        metrics.inc("test_counter", { b = "2", a = "1" })
        h.assert_eq(metrics.get("test_counter", { a = "1", b = "2" }), 2)
    end)
end)

h.describe("metrics gauges", function()
    h.it("sets absolute values", function()
        metrics.reset()
        metrics.set("test_gauge", nil, 42)
        h.assert_eq(metrics.get("test_gauge", nil), 42)
        metrics.set("test_gauge", nil, 7)
        h.assert_eq(metrics.get("test_gauge", nil), 7)
        metrics.set("test_gauge", nil, 0)
        h.assert_eq(metrics.get("test_gauge", nil), 0)
    end)
end)

h.describe("metrics histograms", function()
    h.it("records bucket, sum and count series", function()
        metrics.reset()
        metrics.observe("test_hist", nil, 0.05)
        metrics.observe("test_hist", nil, 5)
        h.assert_eq(metrics.get("test_hist_count", nil), 2)
        h.assert_eq(metrics.get("test_hist_sum", nil), 5.05)
        h.assert_eq(metrics.get("test_hist_bucket", { le = "0.1" }), 1)
        h.assert_eq(metrics.get("test_hist_bucket", { le = "10" }), 2)
        h.assert_eq(metrics.get("test_hist_bucket", { le = "+Inf" }), 2)
    end)
end)

h.describe("metrics label hygiene", function()
    h.it("escapes quotes and backslashes", function()
        h.assert_eq(metrics.encode_labels({ a = 'va"lue' }), '{a="va\\"lue"}')
        h.assert_eq(metrics.encode_labels({ a = "back\\slash" }),
            '{a="back\\\\slash"}')
    end)

    h.it("strips control characters", function()
        h.assert_eq(metrics.encode_labels({ a = "x\r\ny" }), '{a="xy"}')
        h.assert_eq(metrics.encode_labels({ a = "x\0y" }), '{a="xy"}')
    end)

    h.it("truncates very long label values", function()
        local encoded = metrics.encode_labels({ a = string.rep("x", 500) })
        h.assert_true(#encoded < 200, "label value must be truncated")
    end)

    h.it("renders no braces for empty label sets", function()
        h.assert_eq(metrics.encode_labels(nil), "")
        h.assert_eq(metrics.encode_labels({}), "")
    end)
end)

h.describe("metrics cardinality control", function()
    h.it("folds excess series into an overflow bucket", function()
        h.assert_true(metrics.init("ro_metrics", { max_series = 20 }))
        metrics.reset()
        for i = 1, 200 do
            metrics.inc("test_counter", { id = "series-" .. i })
        end
        local overflow = metrics.get("test_counter", nil)
        local rendered = metrics.render()
        h.assert_match(rendered, "ro_overflow")
        h.assert_true(metrics.get("test_counter", { id = "series-199" }) == nil,
            "series beyond the cap must not be tracked individually")
        metrics.init("ro_metrics", { max_series = 20000 })
    end)
end)

h.describe("metrics rendering", function()
    h.it("emits Prometheus text format with HELP and TYPE", function()
        metrics.reset()
        metrics.inc("test_counter", { action = "allow" }, 3)
        local out = metrics.render()
        h.assert_match(out, "# HELP test_counter A counter for tests%.")
        h.assert_match(out, "# TYPE test_counter counter")
        h.assert_match(out, 'test_counter{action="allow"} 3')
        h.assert_match(out, "ro_metrics_series_total")
    end)

    h.it("groups histogram sub-series under their parent metric", function()
        metrics.reset()
        metrics.observe("test_hist", nil, 0.5)
        local out = metrics.render()
        h.assert_match(out, "# TYPE test_hist histogram")
        h.assert_match(out, "test_hist_bucket")
        h.assert_match(out, "test_hist_sum")
        h.assert_match(out, "test_hist_count")
    end)

    h.it("bootstraps the gateway metric catalogue", function()
        h.assert_true(metrics.bootstrap())
        local out = metrics.render()
        h.assert_match(out, "ro_requests_total")
        h.assert_match(out, "ro_denied_total")
        h.assert_match(out, "ro_dns_denials_total")
        h.assert_match(out, "ro_policy_version")
    end)
end)
