local h = require("harness")
local httpd = require("ro.httpd")
local cjson = require("cjson.safe")

h.describe("httpd.parse_query", function()
    h.it("parses simple pairs", function()
        h.assert_deep_eq(httpd.parse_query("a=1&b=two"), { a = "1", b = "two" })
    end)

    h.it("handles keys without values", function()
        h.assert_deep_eq(httpd.parse_query("flag"), { flag = "" })
        h.assert_deep_eq(httpd.parse_query("a=&b=2"), { a = "", b = "2" })
    end)

    h.it("decodes percent-encoding and plus signs", function()
        local q = httpd.parse_query("name=hello%20world&other=a+b&sym=%2F%3A")
        h.assert_eq(q.name, "hello world")
        h.assert_eq(q.other, "a b")
        h.assert_eq(q.sym, "/:")
    end)

    h.it("returns an empty table for empty input", function()
        h.assert_deep_eq(httpd.parse_query(nil), {})
        h.assert_deep_eq(httpd.parse_query(""), {})
    end)

    h.it("drops absurdly large keys and values", function()
        local q = httpd.parse_query(string.rep("k", 500) .. "=1")
        h.assert_deep_eq(q, {})
        q = httpd.parse_query("k=" .. string.rep("v", 5000))
        h.assert_deep_eq(q, {})
    end)
end)

h.describe("httpd response builders", function()
    h.it("builds json responses", function()
        local res = httpd.json(200, { ok = true })
        h.assert_eq(res.status, 200)
        h.assert_eq(res.content_type, "application/json")
        h.assert_deep_eq(cjson.decode(res.body), { ok = true })
    end)

    h.it("builds text responses", function()
        local res = httpd.text(200, "hello")
        h.assert_eq(res.body, "hello")
        h.assert_match(res.content_type, "text/plain")
    end)

    h.it("builds error responses with a stable shape", function()
        local res = httpd.error(403, "forbidden", "nope")
        h.assert_eq(res.status, 403)
        local body = cjson.decode(res.body)
        h.assert_eq(body.error, "forbidden")
        h.assert_eq(body.message, "nope")
    end)

    h.it("builds raw responses with a custom content type", function()
        local res = httpd.response(200, "# HELP x", nil, "text/plain; version=0.0.4")
        h.assert_eq(res.body, "# HELP x")
        h.assert_match(res.content_type, "version=0%.0%.4")
    end)
end)
